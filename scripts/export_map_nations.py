"""Write every map's nations into the bot as each mode's whole-map list.

A game with no preset lists every nation on its map (the website has always
done that). The bot's own lists (NATION_CATEGORIES & co.) are TommyKay's
curated reservation lists, which now live on as TommyKay's presets. This
script gives the bot the whole map too, so presets, nation locks and drafts
can use any nation the map shows.

For each mode it reads the website's map (web/public/maps/*.geojson), names
each nation the way the bot does when the bot's list has it (matched the
same way the website matches names, web/src/data/nationCategories.ts), and
otherwise keeps the map's own name (the name a website reservation stores).
Nations are grouped the way the map's reservation list groups a game with
no preset: factions for the historical mods (plus "Unaligned"), otherwise
Majors and then regions.

The result replaces the block between the MAP_NATION_LAYOUTS markers in
GameMaster Bot/bot.py.py. It also writes GameMaster's own presets (the
curated lists, web/src/data/officialPresets.json) and preview mode's copy of
the bot's lists (web/src/data/demoModeDefaults.json). Run it again after a
map or a bot list changes:

    python scripts/export_map_nations.py          # write
    python scripts/export_map_nations.py --check  # fail if bot.py.py is out of date
"""

from __future__ import annotations

import ast
import hashlib
import json
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOT = ROOT / "GameMaster Bot" / "bot.py.py"
WEB = ROOT / "web"
CATEGORIES_TS = WEB / "src" / "data" / "nationCategories.ts"
TAG_TO_SLOT = WEB / "src" / "lib" / "tag_to_slot.json"
OFFICIAL_JSON = WEB / "src" / "data" / "officialPresets.json"
DEMO_JSON = WEB / "src" / "data" / "demoModeDefaults.json"

START = "# --- MAP_NATION_LAYOUTS (generated by scripts/export_map_nations.py; don't edit by hand) ---"
END = "# --- end of MAP_NATION_LAYOUTS ---"

# Bot mode -> (its map, the bot list it names nations from, how the map groups it).
MODES = {
    "Roleplay": ("road_to_56", "Roleplay", "regions"),
    "Roleplay (Millennium Dawn)": ("modern", "Roleplay (Millennium Dawn)", "regions"),
    "Roleplay (Novum Vexillum)": ("modern", "Roleplay (Novum Vexillum)", "regions"),
    "Kaiserreich (FFA)": ("kaiserreich", "Kaiserreich (FFA)", "regions"),
    "TFR": ("modern", "TFR", "regions"),
    "Historical (Vanilla)": ("vanilla", "Historical (Vanilla)", "regions"),
    "Historical (TFB)": ("tfb", "Historical (TFB)", "factions"),
    "Historical (Oak)": ("oak", "Historical (Oak)", "factions"),
    "Historical (Horst)": ("horst", "Historical (Horst)", "factions"),
    "Historical (BFFU)": ("bffu", "Historical (BFFU)", "factions"),
}
MODERN_MAPS = {"modern"}
# GameMaster's own presets (the bot's curated lists): the name of each mode's one.
OFFICIAL = {
    "Roleplay": "Road to 56",
    "Kaiserreich (FFA)": "FFA",
    "Roleplay (Millennium Dawn)": "Main nations",
    "Roleplay (Novum Vexillum)": "Main nations",
    "TFR": "Five factions",
    "Historical (Vanilla)": "Main factions",
    "Historical (TFB)": "Main factions",
    "Historical (Oak)": "Main factions",
    "Historical (Horst)": "Main factions",
    "Historical (BFFU)": "Main factions",
}
# TommyKay's own two (never in the public library), with their descriptions.
HOME_ONLY = {
    "Roleplay": "TommyKay's Roleplay list: 7 Majors and the 50 Minors we play. Every other nation stays off the list.",
    "Kaiserreich (FFA)": "Free-for-all in four factions: Entente, Third International, Reichspakt and Moscow Accord.",
}
REGION_ORDER = ["Europe", "Middle East", "Asia", "Oceania", "North America", "South America", "Africa", "Other"]
FACTION_ORDER = ["Axis", "Allies", "Comintern", "GEACPS"]
# web/src/data/nationCategories.ts majorTagsFor()
MAJOR_TAGS = {"USA", "ENG", "SOV", "FRA", "GER", "ITA", "JAP"}
KR_MAJOR_TAGS = {"GER", "FRA", "ENG", "USA", "JAP", "RUS", "AUS", "TUR"}


def ts_table(source: str, name: str) -> dict[str, str]:
    """A flat `const NAME: Record<string, X> = { key: "value", ... };` table from TypeScript."""
    match = re.search(rf"const {name}[^=]*=\s*\{{(.*?)\n\}};", source, re.S)
    if not match:
        raise SystemExit(f"Couldn't find {name} in {CATEGORIES_TS}")
    body = re.sub(r"//[^\n]*", "", match.group(1))
    return {key: value for key, value in re.findall(r"([A-Za-z0-9_]+)\s*:\s*\"([^\"]*)\"", body)}


def bot_lists() -> dict[str, dict]:
    """The bot's literal nation lists, read without running the bot."""
    wanted = {"NATION_CATEGORIES", "MILLENNIUM_DAWN_REGIONS", "KAISERREICH_REGIONS", "TFR_DATA"}
    found = {}
    for node in ast.parse(BOT.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id in wanted and target.id not in found:
                    found[target.id] = ast.literal_eval(node.value)
    categories = dict(found["NATION_CATEGORIES"])
    # The assignments the bot makes after the literal (bot.py.py, after NATION_CATEGORIES).
    categories["Historical (BFFU)"] = json.loads(json.dumps(categories["Historical (TFB)"]))
    categories["Roleplay (Millennium Dawn)"] = found["MILLENNIUM_DAWN_REGIONS"]
    categories["Roleplay (Novum Vexillum)"] = found["MILLENNIUM_DAWN_REGIONS"]
    categories["Kaiserreich (FFA)"] = found["KAISERREICH_REGIONS"]
    categories["TFR"] = {
        faction: {"Majors": list(data.get("Majors", [])), "Minors": list(data.get("Minors", []))}
        for faction, data in found["TFR_DATA"]["Factions"].items()
    }
    return categories


def bot_names(lists: dict) -> list[str]:
    names: list[str] = []
    for value in lists.values():
        if isinstance(value, list):
            names.extend(value)
        elif isinstance(value, dict):
            for group in value.values():
                if isinstance(group, list):
                    names.extend(group)
    return list(dict.fromkeys(names))


def main() -> int:
    check = "--check" in sys.argv[1:]
    source = CATEGORIES_TS.read_text(encoding="utf-8")
    aliases = ts_table(source, "NAME_ALIASES")
    regions = ts_table(source, "REGION_BY_TAG")
    modern_regions = ts_table(source, "MODERN_REGION_BY_TAG")
    tag_to_slot = json.loads(TAG_TO_SLOT.read_text(encoding="utf-8"))

    def bare(name: str) -> str:
        """A name without accents, case, spaces or punctuation."""
        ascii_name = "".join(
            char for char in unicodedata.normalize("NFD", name) if not "̀" <= char <= "ͯ"
        ).lower()
        return re.sub(r"[^a-z0-9]", "", ascii_name)

    def canonical(name: str) -> str:
        """web/src/data/nationCategories.ts canonicalName()."""
        return aliases.get(bare(name), bare(name))

    def match_keys(tag: str, slot: str, name: str) -> list[str]:
        """web/src/data/nationCategories.ts nationMatchKeys()."""
        keys = [canonical(slot or name), canonical(name)]
        if tag in tag_to_slot:
            keys.append(canonical(tag_to_slot[tag]))
        return list(dict.fromkeys(keys))

    categories = bot_lists()
    layouts: dict[str, list] = {}
    report = []
    for mode, (map_name, list_key, grouping) in MODES.items():
        geo = json.loads((WEB / "public" / "maps" / f"{map_name}.geojson").read_text(encoding="utf-8"))
        nations: dict[str, tuple[str, str]] = {}
        for feature in geo["features"]:
            props = feature.get("properties") or {}
            if props.get("slot_key") and props.get("tag") not in nations:
                nations[props["tag"]] = (props["slot_key"], props.get("name") or props["slot_key"])
        lists = categories[list_key]
        by_key: dict[str, str] = {}
        for bot_name in bot_names(lists):
            by_key.setdefault(canonical(bot_name), bot_name)

        # Each map nation under its bot name when the bot lists it: the same
        # name first (Taiwan is "Republic of China" on both), then the
        # website's looser matching ("Third French Republic" is France).
        exact = {bare(bot_name): bot_name for bot_name in bot_names(lists)}
        named: dict[str, str] = {}
        used: set[str] = set()
        for tag, (slot, name) in nations.items():
            hit = next((exact[key] for key in (bare(slot), bare(name)) if exact.get(key) not in (None, *used)), None)
            if hit:
                used.add(hit)
                named[tag] = hit
        for tag, (slot, name) in nations.items():
            if tag in named:
                continue
            hit = next((by_key[key] for key in match_keys(tag, slot, name) if key in by_key and by_key[key] not in used), None)
            if hit is None:
                hit = slot
            if hit in used:
                print(f"  {mode}: skipped {tag} ({slot}), its name is taken")
                continue
            used.add(hit)
            named[tag] = hit
        matched = sum(1 for tag in named if named[tag] in by_key.values())

        groups: list[tuple[str, list[tuple[str | None, list[str]]]]] = []
        if grouping == "factions":
            placed: set[str] = set()
            tag_of = {bot: tag for tag, bot in named.items()}
            order = sorted(lists, key=lambda name: FACTION_ORDER.index(name) if name in FACTION_ORDER else 99)
            for faction in order:
                content = lists[faction]
                tiers = []
                for label, members in (content.items() if isinstance(content, dict) else [(None, content)]):
                    on_map = [bot for bot in members if bot in tag_of and bot not in placed]
                    placed.update(on_map)
                    if on_map:
                        tiers.append((label, on_map))
                if tiers:
                    groups.append((faction, tiers))
            rest = sorted(bot for bot in named.values() if bot not in placed)
            if rest:
                groups.append(("Unaligned", [(None, rest)]))
        else:
            majors_tags = KR_MAJOR_TAGS if map_name == "kaiserreich" else MAJOR_TAGS
            majors = sorted(named[tag] for tag in named if tag in majors_tags)
            if majors:
                groups.append(("Majors", [(None, majors)]))
            for region in REGION_ORDER:
                members = []
                for tag, bot in named.items():
                    if tag in majors_tags:
                        continue
                    if tag in ("SOV", "RUS"):
                        where = "Europe"
                    elif map_name in MODERN_MAPS:
                        where = modern_regions.get(tag) or regions.get(tag) or "Other"
                    else:
                        where = regions.get(tag) or "Other"
                    if where == region:
                        members.append(bot)
                if members:
                    groups.append((region, [(None, sorted(members))]))
        layouts[mode] = groups
        missing = [bot for bot in bot_names(lists) if bot not in named.values()]
        report.append(f"{mode}: {len(named)} on the map, {matched} named as the bot does, "
                      f"{len(missing)} bot nations not on the map"
                      + (f" ({', '.join(missing)})" if missing and "--verbose" in sys.argv[1:] else ""))

    official = official_presets(categories)
    demo = demo_defaults(categories, layouts)

    lines = [START, "# Every nation on each mode's map, grouped like the map's reservation list:",
             "# {mode: [(group, [(sub-group | None, [nation, ...]), ...]), ...]}.", "MAP_NATION_LAYOUTS = {"]
    for mode, groups in layouts.items():
        lines.append(f"    {json.dumps(mode)}: [")
        for group, tiers in groups:
            lines.append(f"        ({json.dumps(group)}, [")
            for label, members in tiers:
                lines.append(f"            ({json.dumps(label) if label else 'None'}, [")
                for start in range(0, len(members), 4):
                    lines.append("                " + " ".join(f"{json.dumps(m, ensure_ascii=False)}," for m in members[start:start + 4]))
                lines.append("            ]),")
            lines.append("        ]),")
        lines.append("    ],")
    lines += ["}", END]
    block = "\n".join(lines)

    bot_source = BOT.read_text(encoding="utf-8")
    if START not in bot_source:
        raise SystemExit(f"Add the two marker lines to {BOT} first:\n{START}\n{END}")
    before, rest = bot_source.split(START, 1)
    outputs = {
        BOT: before + block + rest.split(END, 1)[1],
        OFFICIAL_JSON: json.dumps(official, indent=2, ensure_ascii=False) + "\n",
        DEMO_JSON: json.dumps(demo, indent=2, ensure_ascii=False) + "\n",
    }
    print("\n".join(report))
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
    if check:
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date: run python scripts/export_map_nations.py")
        if not stale:
            print("Everything is up to date.")
        return 1 if stale else 0
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8", newline="\n")
        print(f"Wrote {path.relative_to(ROOT)}.")
    if not stale:
        print("Everything was already up to date.")
    return 0


def tiers_of(content) -> list[tuple[str | None, list[str]]]:
    """A bot list entry as sub-groups: a flat list is one, a faction dict one per key."""
    if isinstance(content, dict):
        return [(label, list(nations)) for label, nations in content.items() if isinstance(nations, list) and nations]
    return [(None, list(content))] if content else []


def bot_majors(mode: str, lists: dict) -> list[str]:
    """bot.py.py get_major_nations_for_mode()."""
    majors = list(lists.get("Majors", [])) if isinstance(lists.get("Majors"), list) else []
    for content in lists.values():
        if isinstance(content, dict) and isinstance(content.get("Majors"), list):
            majors.extend(content["Majors"])
    return list(dict.fromkeys(majors))


def official_presets(categories: dict) -> dict:
    """GameMaster's own presets: TommyKay's curated lists (bot.py.py), one per
    mode. Road to 56 and FFA stay TommyKay's; the rest are in the public
    library. web/src/lib/presetStore.ts keeps them in the presets table."""
    presets = []
    for mode, name in OFFICIAL.items():
        lists = categories[mode]
        groups = [(group, tiers_of(content)) for group, content in lists.items()]
        groups = [(group, tiers) for group, tiers in groups if tiers]
        majors = bot_majors(mode, lists)
        total = len({nation for _group, tiers in groups for _label, nations in tiers for nation in nations})
        names = [group for group, _tiers in groups]
        if mode in HOME_ONLY:
            description = HOME_ONLY[mode]
        elif isinstance(next(iter(lists.values())), dict):
            joined = ", ".join(names[:-1]) + f" and {names[-1]}" if len(names) > 1 else names[0]
            description = f"{joined}, with the {total} nations most games play."
        else:
            description = f"{len(majors)} Majors and the regional Minors most games play ({total} nations)."
        presets.append({
            "preset_id": hashlib.md5(f"gamemaster-official-preset:{mode}".encode()).hexdigest(),
            "mode": mode,
            "name": name,
            "description": description,
            "home_only": mode in HOME_ONLY,
            "data": {
                "layout": [
                    {
                        "id": f"gm-{index + 1}",
                        "name": group,
                        "enabled": True,
                        "builtin": False,
                        "tiers": [{"label": label, "nations": nations} for label, nations in tiers],
                    }
                    for index, (group, tiers) in enumerate(groups)
                ],
                "nation_locks": [],
                "major_lock_level": "Trusted",
                "minor_lock_level": "All Users",
                "rules": None,
                "mods": None,
                "require_ironlegion": None,
            },
        })
    return {
        "_about": "Generated by scripts/export_map_nations.py from the bot's curated lists. Don't edit by hand.",
        "presets": presets,
    }


def demo_defaults(categories: dict, layouts: dict) -> dict:
    """Preview mode's copy of what the bot publishes (web_moderation_options):
    each mode's nations and standard groups, now the whole map."""
    demo = json.loads(DEMO_JSON.read_text(encoding="utf-8"))
    for mode, groups in layouts.items():
        lists = categories[MODES[mode][1]]
        majors = set(bot_majors(mode, lists))
        everything = sorted(set(bot_names(lists)) | {n for _g, tiers in groups for _l, ns in tiers for n in ns})
        demo["mode_nations"][mode] = {
            "majors": [nation for nation in everything if nation in majors],
            "minors": [nation for nation in everything if nation not in majors],
        }
        demo["mode_layouts"][mode] = [
            {"name": group, "tiers": [{"label": label, "nations": nations} for label, nations in tiers]}
            for group, tiers in groups
        ]
    return demo


if __name__ == "__main__":
    raise SystemExit(main())
